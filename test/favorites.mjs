import assert from 'node:assert/strict';
import fs from 'node:fs';
const data = new Map();
globalThis.localStorage = {getItem:key=>data.get(key)??null,setItem:(key,value)=>data.set(key,value)};
const source = fs.readFileSync(new URL('../public/favorites.js', import.meta.url), 'utf8');
const f = await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
assert.deepEqual([...f.parseFavorites('[1,1,-1,0,"2",null,3]')], [1,3]);
assert.equal(f.parseFavorites('{broken').size, 0);
assert.equal(f.parseFavorites('{}').size, 0);
assert.deepEqual(f.toggleFavorite(7), {active:true,saved:true});
f.syncFavorites();
assert.equal(f.hasFavorite(7), true);
data.set(f.FAVORITES_KEY, '[7,8]');
f.toggleFavorite(9);
assert.deepEqual(JSON.parse(data.get(f.FAVORITES_KEY)), [7,8,9]);
f.toggleFavorite(7);
assert.equal(f.hasFavorite(7), false);
assert.throws(()=>f.toggleFavorite(-1));
globalThis.localStorage.setItem = ()=>{throw new Error('quota');};
assert.equal(f.toggleFavorite(10).saved, false);
f.toggleFavorite(11);
assert.equal(f.hasFavorite(10), true);
assert.equal(f.hasFavorite(11), true);
f.toggleFavorite(10);
assert.equal(f.hasFavorite(10), false);
console.log('Favorites checks passed: persistence, invalid data, other tabs, remove, storage failure.');
